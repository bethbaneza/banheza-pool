// Banheza Pool — sistema de idiomas (PT/EN/ES). Independente do `state` do app.js: idioma é
// preferência do dispositivo/navegador, não deve ser apagada quando a pessoa desloga.
// Uso: t('chave') devolve o texto no idioma atual; t('chave', {var: valor}) substitui
// "{var}" dentro do texto. Chave ausente cai para português, e por fim para a própria chave
// (nunca quebra a tela, só mostra algo "estranho" que é fácil de notar e corrigir).

const IDIOMAS_SUPORTADOS = ['pt', 'en', 'es'];

function idiomaInicial() {
  try {
    const salvo = localStorage.getItem('bp_idioma');
    if (IDIOMAS_SUPORTADOS.includes(salvo)) return salvo;
  } catch (e) { /* localStorage indisponível — segue com o padrão */ }
  return 'pt';
}
let idioma = idiomaInicial();

function definirIdioma(novo) {
  if (!IDIOMAS_SUPORTADOS.includes(novo)) return;
  idioma = novo;
  try { localStorage.setItem('bp_idioma', novo); } catch (e) { /* ignora */ }
  document.documentElement.lang = novo === 'pt' ? 'pt-BR' : novo;
}

function t(chave, vars) {
  const dict = TRADUCOES[idioma] || TRADUCOES.pt;
  let texto = dict[chave];
  if (texto == null) texto = TRADUCOES.pt[chave];
  if (texto == null) return chave;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      texto = texto.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return texto;
}

